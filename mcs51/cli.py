def _parse_int(value: str) -> int:
    upper = value.upper()
    if upper.endswith("H") and upper[:-1]:
        return int(upper[:-1], 16)
    return int(value, 0)


def _parse_hex_bytes(value: str) -> bytes:
    compact = value.replace(" ", "").replace(",", "").replace("_", "")
    if compact.startswith("0x"):
        compact = compact[2:]
    if len(compact) % 2:
        raise ValueError("serial input hex must contain an even number of hex digits")
    return bytes.fromhex(compact)


